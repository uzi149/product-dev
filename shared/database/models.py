"""SQLAlchemy models for the tables in Technical Scope §5.2, with the §5.3 indexes.

Times are `timestamptz` (UTC). Primary keys are UUIDs generated by the database.
Status-like columns are text with a CHECK constraint built from the StrEnums below.
"""

import enum
import uuid
from datetime import datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

# Fixed per installation (ADR 0006): bge-base-en-v1.5 text, siglip-base-patch16-224 image.
EMBEDDING_DIM = 768


class SourceType(enum.StrEnum):
    RTSP = "rtsp"
    FILE = "file"


class ProcessingStatus(enum.StrEnum):
    PENDING = "pending"
    PROCESSING = "processing"
    DONE = "done"
    FAILED = "failed"


class HealthStatus(enum.StrEnum):
    OK = "ok"
    OFFLINE = "offline"


class EmbeddingType(enum.StrEnum):
    DESCRIPTION = "description"


class EventStatus(enum.StrEnum):
    NEW = "new"
    CONFIRMED = "confirmed"
    DISMISSED = "dismissed"


def _one_of(column: str, values: type[enum.StrEnum], name: str) -> CheckConstraint:
    allowed = ", ".join(f"'{v.value}'" for v in values)
    return CheckConstraint(f"{column} IN ({allowed})", name=name)


class Base(DeclarativeBase):
    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(table_name)s_%(column_0_N_name)s",
            "uq": "uq_%(table_name)s_%(column_0_N_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


def _timestamp(**kw: Any) -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), **kw)


class Camera(Base):
    __tablename__ = "cameras"
    __table_args__ = (_one_of("source_type", SourceType, "source_type"),)

    id: Mapped[uuid.UUID] = _uuid_pk()
    display_name: Mapped[str] = mapped_column(String(200))
    source_type: Mapped[str] = mapped_column(String(20))
    # Fernet-encrypted; never returned by the API.
    source_uri_encrypted: Mapped[str | None] = mapped_column(Text)
    enabled: Mapped[bool] = mapped_column(Boolean, server_default=text("true"))
    analysis_fps: Mapped[int] = mapped_column(Integer, server_default=text("1"))
    retention_days: Mapped[int] = mapped_column(Integer, server_default=text("14"))
    # Mask polygons and change thresholds (scope §7.3).
    detection_config: Mapped[dict[str, Any]] = mapped_column(
        JSONB, server_default=text("'{}'::jsonb")
    )
    created_at: Mapped[datetime] = _created_at()

    segments: Mapped[list["VideoSegment"]] = relationship(
        back_populates="camera", cascade="all, delete-orphan", passive_deletes=True
    )


class VideoSegment(Base):
    """One stored interval of active footage. `status` is the analysis state."""

    __tablename__ = "video_segments"
    __table_args__ = (
        _one_of("status", ProcessingStatus, "status"),
        Index("ix_video_segments_camera_id_start_time", "camera_id", "start_time"),
        Index("ix_video_segments_end_time", "end_time"),
        Index("ix_video_segments_status", "status"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    camera_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("cameras.id", ondelete="CASCADE"))
    start_time: Mapped[datetime] = _timestamp()
    end_time: Mapped[datetime] = _timestamp()
    duration_ms: Mapped[int] = mapped_column(BigInteger)
    storage_uri: Mapped[str] = mapped_column(Text)
    activity_score: Mapped[float | None] = mapped_column(Float)
    status: Mapped[str] = mapped_column(String(20), server_default=ProcessingStatus.PENDING.value)
    codec: Mapped[str | None] = mapped_column(String(50))
    width: Mapped[int | None] = mapped_column(Integer)
    height: Mapped[int | None] = mapped_column(Integer)
    created_at: Mapped[datetime] = _created_at()

    camera: Mapped[Camera] = relationship(back_populates="segments")
    windows: Mapped[list["AnalysisWindow"]] = relationship(
        back_populates="segment", cascade="all, delete-orphan", passive_deletes=True
    )


class StaticPeriod(Base):
    """The camera stayed operational but its scene did not materially change."""

    __tablename__ = "static_periods"
    __table_args__ = (
        _one_of("health_status", HealthStatus, "health_status"),
        Index("ix_static_periods_camera_id_start_time", "camera_id", "start_time"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    camera_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("cameras.id", ondelete="CASCADE"))
    start_time: Mapped[datetime] = _timestamp()
    end_time: Mapped[datetime] = _timestamp()
    reference_frame_uri: Mapped[str | None] = mapped_column(Text)
    health_status: Mapped[str] = mapped_column(String(20), server_default=HealthStatus.OK.value)


class AnalysisWindow(Base):
    """camera_id is repeated here so camera + time filters need no join (scope §5.3)."""

    __tablename__ = "analysis_windows"
    __table_args__ = (
        _one_of("processing_status", ProcessingStatus, "processing_status"),
        Index("ix_analysis_windows_camera_id_start_time", "camera_id", "start_time"),
        Index("ix_analysis_windows_end_time", "end_time"),
        Index("ix_analysis_windows_segment_id", "segment_id"),
        Index("ix_analysis_windows_processing_status", "processing_status"),
        Index(
            "ix_analysis_windows_vlm_description_fts",
            text("to_tsvector('english', vlm_description)"),
            postgresql_using="gin",
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    segment_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("video_segments.id", ondelete="CASCADE")
    )
    camera_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("cameras.id", ondelete="CASCADE"))
    start_time: Mapped[datetime] = _timestamp()
    end_time: Mapped[datetime] = _timestamp()
    vlm_description: Mapped[str | None] = mapped_column(Text)
    structured_observation_json: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    vlm_model: Mapped[str | None] = mapped_column(String(200))
    confidence: Mapped[float | None] = mapped_column(Float)
    processing_status: Mapped[str] = mapped_column(
        String(20), server_default=ProcessingStatus.PENDING.value
    )

    segment: Mapped[VideoSegment] = relationship(back_populates="windows")
    keyframes: Mapped[list["Keyframe"]] = relationship(
        back_populates="window", cascade="all, delete-orphan", passive_deletes=True
    )
    text_embeddings: Mapped[list["TextEmbedding"]] = relationship(
        back_populates="window", cascade="all, delete-orphan", passive_deletes=True
    )


class Keyframe(Base):
    __tablename__ = "keyframes"
    __table_args__ = (
        Index("ix_keyframes_analysis_window_id", "analysis_window_id"),
        Index(
            "ix_keyframes_visual_embedding_hnsw",
            "visual_embedding",
            postgresql_using="hnsw",
            postgresql_ops={"visual_embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    analysis_window_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("analysis_windows.id", ondelete="CASCADE")
    )
    timestamp: Mapped[datetime] = _timestamp()
    storage_uri: Mapped[str] = mapped_column(Text)
    visual_embedding: Mapped[list[float] | None] = mapped_column(Vector(EMBEDDING_DIM))

    window: Mapped[AnalysisWindow] = relationship(back_populates="keyframes")


class TextEmbedding(Base):
    __tablename__ = "text_embeddings"
    __table_args__ = (
        _one_of("embedding_type", EmbeddingType, "embedding_type"),
        Index("ix_text_embeddings_analysis_window_id", "analysis_window_id"),
        Index(
            "ix_text_embeddings_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    analysis_window_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("analysis_windows.id", ondelete="CASCADE")
    )
    embedding_type: Mapped[str] = mapped_column(
        String(30), server_default=EmbeddingType.DESCRIPTION.value
    )
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM))
    source_text: Mapped[str] = mapped_column(Text)

    window: Mapped[AnalysisWindow] = relationship(back_populates="text_embeddings")


class Trigger(Base):
    __tablename__ = "triggers"

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(String(200))
    natural_language_rule: Mapped[str] = mapped_column(Text)
    compiled_rule_json: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    minimum_confidence: Mapped[float] = mapped_column(Float, server_default=text("0.8"))
    cooldown_seconds: Mapped[int] = mapped_column(Integer, server_default=text("120"))
    pre_roll_seconds: Mapped[int] = mapped_column(Integer, server_default=text("10"))
    post_roll_seconds: Mapped[int] = mapped_column(Integer, server_default=text("20"))
    enabled: Mapped[bool] = mapped_column(Boolean, server_default=text("true"))
    created_at: Mapped[datetime] = _created_at()

    cameras: Mapped[list[Camera]] = relationship(secondary="trigger_cameras")


class TriggerCamera(Base):
    __tablename__ = "trigger_cameras"
    __table_args__ = (Index("ix_trigger_cameras_camera_id", "camera_id"),)

    trigger_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("triggers.id", ondelete="CASCADE"), primary_key=True
    )
    camera_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("cameras.id", ondelete="CASCADE"), primary_key=True
    )


class Event(Base):
    __tablename__ = "events"
    __table_args__ = (
        _one_of("status", EventStatus, "status"),
        Index("ix_events_trigger_id", "trigger_id"),
        Index("ix_events_camera_id_start_time", "camera_id", "start_time"),
        Index("ix_events_end_time", "end_time"),
        Index("ix_events_status", "status"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    trigger_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("triggers.id"))
    camera_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("cameras.id"))
    start_time: Mapped[datetime] = _timestamp()
    end_time: Mapped[datetime] = _timestamp()
    confidence: Mapped[float | None] = mapped_column(Float)
    summary: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String(20), server_default=EventStatus.NEW.value)
    created_at: Mapped[datetime] = _created_at()

    evidence: Mapped[list["EventEvidence"]] = relationship(
        back_populates="event",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="EventEvidence.sequence_order",
    )


class EventEvidence(Base):
    """segment_id is RESTRICT: footage used as evidence is protected from deletion (ADR 0007)."""

    __tablename__ = "event_evidence"
    __table_args__ = (
        Index("ix_event_evidence_event_id", "event_id"),
        Index("ix_event_evidence_segment_id", "segment_id"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    event_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("events.id", ondelete="CASCADE"))
    segment_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("video_segments.id", ondelete="RESTRICT")
    )
    start_offset_ms: Mapped[int] = mapped_column(BigInteger)
    end_offset_ms: Mapped[int] = mapped_column(BigInteger)
    evidence_reason: Mapped[str | None] = mapped_column(Text)
    sequence_order: Mapped[int] = mapped_column(Integer, server_default=text("0"))

    event: Mapped[Event] = relationship(back_populates="evidence")


